export function useTranslation() {
  const language = useSettingsStore((state) => state.language);

  return {
    t: (key: string): string => {
      if (language === 'default' || !TRANSLATIONS[key]) return key;
      return TRANSLATIONS[key][language] || TRANSLATIONS[key]['en'] || key;
    },
    language,
  };
}